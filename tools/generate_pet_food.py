"""Builds Data/PetFood.lua from the Forever client's tables on wago.tools.

Every item a hunter's pet can eat: items with a pet diet (Item.ItemPetFoodID) that are consumables,
trade goods or miscellaneous items (quest items and the odd weapon are left out), with the diet name
(as GetPetFoodTypes returns it), the item level (pets refuse food far below their level) and whether
the item is conjured (ItemSparse flag 0x2).

Usage:
  python tools/generate_pet_food.py [--build 1.60.1.70532] [--data DIR]
"""
import argparse
import csv
import io
import json
import os
import urllib.request
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "NullgatesPetAmmo-Forever", "Data", "PetFood.lua")
TABLES = ("Item", "ItemSparse", "ItemPetFood")
KEEP_CLASSES = {"0", "7", "15"}   # consumable, trade goods, miscellaneous
CONJURED = 0x2


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "NullgatesPetAmmo-generator"})
    with urllib.request.urlopen(req, timeout=300) as resp:
        return resp.read().decode("utf-8")


def latest_build():
    return json.loads(fetch("https://wago.tools/api/builds/latest"))["wow_classic_beta"]["version"]


def load(name, build, data_dir):
    if data_dir:
        with open(os.path.join(data_dir, name + ".csv"), encoding="utf-8") as f:
            text = f.read()
    else:
        text = fetch("https://wago.tools/db2/%s/csv?build=%s" % (name, build))
    return list(csv.DictReader(io.StringIO(text)))


def to_int(value):
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return 0


def build(t):
    diets = {r["ID"]: r["Name_lang"] for r in t["ItemPetFood"]}
    sparse = {r["ID"]: r for r in t["ItemSparse"]}
    foods = defaultdict(list)
    for r in t["Item"]:
        diet = diets.get(r["ItemPetFoodID"])
        s = sparse.get(r["ID"])
        if not diet or not s or r["ClassID"] not in KEEP_CLASSES or not s.get("Display_lang"):
            continue
        foods[diet].append({"item": to_int(r["ID"]), "level": max(1, to_int(s["ItemLevel"])),
                            "conjured": bool(to_int(s.get("Flags_0")) & CONJURED), "name": s["Display_lang"]})
    for diet in foods:
        foods[diet].sort(key=lambda f: (f["level"], f["item"]))
    return dict(sorted(foods.items()))


def write(build_id, foods):
    lines = [
        "-- Generated by tools/generate_pet_food.py from the Forever client data. Do not edit by hand.",
        "local _, ns = ...",
        "",
        'ns.PET_FOOD_DATA_BUILD = "%s"' % build_id,
        "",
        "-- [itemID] = { diet, item level, conjured }",
        "ns.PET_FOOD = {",
    ]
    for diet, entries in foods.items():
        lines.append("    -- %s (%d)" % (diet, len(entries)))
        for f in entries:
            lines.append('    [%d] = { "%s", %d%s }, -- %s' % (f["item"], diet, f["level"], ", true" if f["conjured"] else "",
                                                          f["name"].replace("\n", " ")))
    lines.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--build")
    parser.add_argument("--data")
    args = parser.parse_args()
    build_id = args.build or latest_build()
    foods = build({name: load(name, build_id, args.data) for name in TABLES})
    write(build_id, foods)
    for diet, entries in foods.items():
        print("%-9s %d" % (diet, len(entries)))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
